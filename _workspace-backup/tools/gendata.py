# regenerates src/g9z_c0_data.txt: mission pool (from tools/missions.mjs) + embedded radio voice-line clips (previews/voicelines/*.mp3)
import base64,subprocess,glob,os
js=subprocess.check_output(['node','tools/missions.mjs','js'],text=True).strip()
clips={os.path.basename(f)[:-4]:base64.b64encode(open(f,'rb').read()).decode() for f in sorted(glob.glob('previews/voicelines/*.mp3'))}
out='// ===================== V8 DROP 2 data (generated by tools/gendata.py - do not hand edit) =====================\n'+js+'\n'
out+='const VOICE_CLIPS={'+','.join(f"{k}:'data:audio/mpeg;base64,{v}'" for k,v in clips.items())+'};\n'
open('src/g9z_c0_data.txt','w').write(out);print(len(out),list(clips))
